const {launchBrowser, targetUrl, screenshotPath, waitForLayout}=require('./helpers/browser.cjs');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await launchBrowser();
  try{
    const page=await browser.newPage({viewport:{width:1060,height:900},deviceScaleFactor:1});
    const errors=[];page.on('pageerror',e=>errors.push({message:e.message,stack:e.stack}));
    await page.goto(targetUrl);
    const app=page;await app.locator('canvas').waitFor();
    const frame=page;
    const restore=async(view,screenMm=315)=>frame.evaluate(({view,screenMm})=>window.dispatchEvent(new CustomEvent('openai:set_globals',{detail:{globals:{widgetState:{modelContent:{view,screenMm,filter:'none',light:true},privateContent:{labels:true,values:true}}}}})),{view,screenMm});
    const canvas=app.locator('canvas');
    await restore('optics');
    await app.locator('#optics-xp-sketch').screenshot({path:screenshotPath('xp-optics-projector-fixed.png')});
    await restore('screen');
    const bounds=await canvas.boundingBox();
    await page.mouse.move(bounds.x+bounds.width*.57,bounds.y+bounds.height*.4);
    assert.equal(await canvas.getAttribute('data-ruler-active'),'true');
    assert.equal(await canvas.evaluate(c=>c.style.cursor),'crosshair');
    assert.equal(await app.locator('.xp-hover').isVisible(),false,'No screen-coordinate tooltip in close screen view');
    const first=Number(await canvas.getAttribute('data-ruler-mm'));
    assert.ok(first>0&&first<110);
    await page.mouse.move(bounds.x+bounds.width*.60,bounds.y+bounds.height*.4);
    const second=Number(await canvas.getAttribute('data-ruler-mm'));
    assert.ok(second>first,'Screen ruler follows the pointer');
    await app.locator('#optics-xp-sketch').screenshot({path:screenshotPath('xp-screen-ruler.png')});
    await page.mouse.down();
    await page.mouse.move(bounds.x+bounds.width*.63,bounds.y+bounds.height*.47,{steps:4});
    assert.notEqual(await canvas.evaluate(c=>c.style.cursor),'grabbing');
    await page.mouse.up();
    await app.locator('[data-move="10"]').click();
    assert.match(await app.locator('[data-live]').textContent(),/320/,'Pointer dragging did not move the screen, and the arrow aligns 315 to 320');
    await app.locator('[data-move="-10"]').click();
    await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+bounds.height*.4);
    assert.equal(await canvas.getAttribute('data-ruler-mm'),'0','Central zero of screen ruler');
    await app.locator('[data-labels]').uncheck();
    await page.mouse.move(bounds.x+bounds.width*.57,bounds.y+bounds.height*.4);
    assert.equal(await canvas.getAttribute('data-ruler-active'),'true','Values keep the ruler visible when names are disabled');
    await app.locator('[data-values]').uncheck();
    await page.mouse.move(bounds.x+bounds.width*.57,bounds.y+bounds.height*.4);
    assert.equal(await canvas.getAttribute('data-ruler-active'),'false');
    assert.equal(await canvas.evaluate(c=>c.style.cursor),'default');
    const disabledImage=await canvas.evaluate(c=>c.toDataURL());
    await page.mouse.move(bounds.x+bounds.width*.60,bounds.y+bounds.height*.45);
    assert.equal(await canvas.evaluate(c=>c.toDataURL()),disabledImage,'No ruler while values are disabled');
    await app.locator('[data-labels]').check();
    await page.mouse.move(bounds.x+bounds.width*.57,bounds.y+bounds.height*.4);
    assert.equal(await canvas.getAttribute('data-ruler-active'),'false','Names alone do not enable the ruler');
    await app.locator('[data-values]').check();
    await page.mouse.move(bounds.x+bounds.width*.57,bounds.y+bounds.height*.4);
    assert.equal(await canvas.getAttribute('data-ruler-active'),'true');
    await page.mouse.move(bounds.x+3,bounds.y+3);
    assert.equal(await canvas.getAttribute('data-ruler-active'),'false','No ruler outside screen face');
    await frame.evaluate(()=>{
      window.__guideText=[];
      const original=CanvasRenderingContext2D.prototype.fillText;
      CanvasRenderingContext2D.prototype.fillText=function(text,x,y,...args){
        if(this.canvas===document.querySelector('#optics-xp-sketch canvas'))window.__guideText.push({text:String(text),x,y});
        return original.call(this,text,x,y,...args);
      };
    });
    await restore('top');
    const indicators=await frame.evaluate(()=>[315,810,855,900,955].map(mm=>({mm,found:window.__guideText.some(p=>p.text===String(mm)||p.text===mm+' мм')})));
    assert.ok(indicators.every(p=>p.found),'Each optical plane has a numbered position indicator: '+JSON.stringify(indicators));
    await app.locator('#optics-xp-sketch').screenshot({path:screenshotPath('xp-top-position-pointers.png')});
    await frame.evaluate(()=>window.__guideText=[]);
    await app.locator('[data-values]').uncheck();
    const disabledNumbers=await frame.evaluate(()=>window.__guideText.filter(p=>/^(315|810|855|900|955)(?:\s*мм)?$/.test(p.text)));
    assert.deepEqual(disabledNumbers,[],'Position values disappear independently of device names');
    await app.locator('[data-labels]').uncheck();
    await frame.evaluate(()=>window.__guideText=[]);
    await app.locator('[data-values]').check();
    assert.equal(await frame.evaluate(()=>window.__guideText.some(p=>/^855(?:\s*мм)?$/.test(p.text))),true,'Position values remain available without device names');
    await page.setViewportSize({width:375,height:900});
    await waitForLayout(page);
    await restore('optics');
    await app.locator('#optics-xp-sketch').screenshot({path:screenshotPath('xp-optics-projector-375.png')});
    await restore('screen');
    const narrow=await canvas.boundingBox();
    await page.mouse.move(narrow.x+narrow.width*.65,narrow.y+narrow.height*.45);
    assert.equal(await canvas.getAttribute('data-ruler-active'),'true');
    await app.locator('#optics-xp-sketch').screenshot({path:screenshotPath('xp-screen-ruler-375.png')});
    console.log(JSON.stringify({errors,indicators,checks:'Independent names/values, ruler on/off, zero, pointer tracking, no close-up dragging/coordinate tooltip; numbered optical-plane markers; projector and mobile screenshots'},null,2));
    if(errors.length)process.exitCode=1;
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
